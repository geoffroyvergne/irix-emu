/*
 * GL pass-through protocol between the IRIX guest library (glpass/guest) and
 * the emulator (glpass/host). Plain C, included by both sides.
 *
 * The guest calls the emulator with the hypercall instruction word
 * GLP_HYPERCALL_WORD (a reserved SPECIAL encoding on the R5000):
 *   a0 = service, a1 = operation, a2 = guest buffer address, a3 = length/arg
 *   v0 = result (negative = error), v1 = extra result
 * Buffers are big-endian 32-bit words, as the guest writes them.
 *
 * Command stream (GLP_OP_SUBMIT): a sequence of records
 *   word 0: (command << 16) | payload_words, or (command << 16) | 0xFFFF
 *           followed by a word holding payload_words (long records)
 *   payload words: ints/enums as-is, floats as IEEE single bits, doubles as
 *   two words (high first).
 * Commands are the GLP_FN_* numbers of glpass_fn.h (generated by
 * glpass/tools/glpass-gen.py from the IRIX gl.h) plus the GLP_FN_ records below.
 */
#ifndef GLPASS_PROTOCOL_H
#define GLPASS_PROTOCOL_H

#define GLP_HYPERCALL_WORD 0x00000668u

/* Services (a0) */
#define GLP_SERVICE_PING 0x00000000u /* v0 = GLP_PING_MAGIC, v1 = protocol version */
#define GLP_SERVICE_GL   0x0000474Cu /* "GL" */

#define GLP_PING_MAGIC   0x1D1E5u
#define GLP_VERSION      2u
#define GLP_ERR_TABLE    (-2) /* HELLO: the guest library was built from other sources than the emulator */

/* GL operations (a1) */
#define GLP_OP_HELLO          0u /* a3 = GLP_FN_TABLE_ID; v0 = GLP_VERSION when host GL is available and the
                                    command tables match, GLP_ERR_TABLE when they differ, else < 0 */
#define GLP_OP_CREATE_CONTEXT 1u /* a3 = share context id (0 = none); v0 = context id */
#define GLP_OP_DESTROY_CONTEXT 2u /* a3 = context id */
#define GLP_OP_MAKE_CURRENT   3u /* a2 -> { context, drawable, width, height } (drawable 0 = release) */
#define GLP_OP_SUBMIT         4u /* a2 -> command stream, a3 = bytes */
#define GLP_OP_SWAP           5u /* a2 -> { drawable, x, y, width, height, key, flags } (screen coordinates) */
#define GLP_OP_FINISH         6u /* wait for the host; nothing to return */
#define GLP_OP_QUERY          7u /* a2 -> { command, reply address, reply bytes, arguments... }, a3 = bytes;
                                    v0 = result. The host writes the reply (big-endian words, raw bytes for
                                    images) into guest memory; the stream is flushed first. */

/* GLP_OP_SWAP flags */
#define GLP_SWAP_BACK_TO_FRONT 1u /* glXSwapBuffers: copy the back buffer to the front first */
#define GLP_SWAP_NO_DISPLAY    2u /* a pixmap or pbuffer: nothing to show on screen */

/* Record length escape */
#define GLP_LONG_RECORD 0xFFFFu

/* Records that are not single GL commands (below the generated numbers). */
#define GLP_FN_CLIENT_DRAW  0x10u /* client vertex arrays, see glpass.c client_draw() */
#define GLP_FN_READ_DRAWABLE 0x11u /* query: { width, height } -> RGBA8 front buffer, bottom row first */
#define GLP_FN_PALETTE      0x12u /* { flags, count, 0x00RRGGBB... }: the current drawable is colour index */

/* Colour index emulation: a colour-index drawable stores index i in its host
   buffer spread over the channels, R = bits 0-7, G = bits 8-9, B = bit 10,
   A = bit 11, so pixel copies and logic operations act on indices, and an
   index write mask on whole bit groups (the high planes overlay emulation
   uses) becomes a colour mask; the palette turns indices into colours when
   the image is shown. */
#define GLP_INDEX_R(i) ((i) & 0xFFu)
#define GLP_INDEX_G(i) (((i) >> 8) & 3u)
#define GLP_INDEX_B(i) (((i) >> 10) & 1u)
#define GLP_INDEX_A(i) (((i) >> 11) & 1u)
#define GLP_INDEX_FROM_RGBA(r, g, b, a) \
    ((unsigned)(r) | ((unsigned)(g) & 3u) << 8 | ((unsigned)(b) & 1u) << 10 | ((unsigned)(a) & 1u) << 11)
#define GLP_PALETTE_OVERLAY 1u /* an overlay-plane drawable: index 0 is transparent */

/* Overlay-plane windows live in the popup planes; the guest fills them with
   this popup value, where the emulator shows their image (GLP_OP_SWAP key). */
#define GLP_OVERLAY_KEY 3u

/* GLP_FN_CLIENT_DRAW kinds */
#define GLP_DRAW_ARRAYS   0u
#define GLP_DRAW_ELEMENTS 1u
#define GLP_DRAW_ELEMENT  2u /* glArrayElement: one element, between glBegin and glEnd */

/* The colour the guest paints its GL windows with: the overlay shows only
   where the window's own pixels hold it, so other windows stay on top. */
#define GLP_DEFAULT_KEY 0xC7u

#endif
